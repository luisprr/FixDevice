const selectors = {
  contactForm: "#contactForm",
  subscribeForm: "#subscribeForm",
  menuToggle: ".menu-toggle",
  headerActions: ".header-actions",
  navBackdrop: ".nav-backdrop",
  langButtons: ".lang-button",
};

let currentLanguage = localStorage.getItem("fixdevice-language") || "es";

const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];

function setText(selector, value) {
  const element = $(selector);
  if (element) element.textContent = value;
}

function setHTML(selector, value) {
  const element = $(selector);
  if (element) element.innerHTML = value;
}

function setPlaceholder(selector, value) {
  const element = $(selector);
  if (element) element.placeholder = value;
}

function setMenu(open) {
  const menuToggle = $(selectors.menuToggle);
  const t = translations[currentLanguage];

  document.body.classList.toggle("menu-open", open);
  menuToggle?.setAttribute("aria-expanded", String(open));
  menuToggle?.setAttribute("aria-label", open ? t.menuClose : t.menuOpen);
}

function applyLanguage(language) {
  currentLanguage = translations[language] ? language : "es";
  const t = translations[currentLanguage];

  document.documentElement.lang = currentLanguage;
  if ($(".hero")) {
    document.querySelector("meta[name='description']")?.setAttribute("content", t.metaDescription);
  }

  $$(".main-nav a").forEach((link, index) => {
    link.innerHTML = t.nav[index];
  });

  setHTML(".hero h1", t.heroTitle);
  $$(".service-strip__item span").forEach((item, index) => {
    item.textContent = t.categories[index];
  });

  setHTML(".intro h2", t.introTitle);
  setText(".intro p", t.introText);
  setText(".about h2", t.aboutTitle);
  setText(".about__copy p:nth-of-type(1)", t.aboutText);
  setHTML(".about__copy p:nth-of-type(2)", t.founders);

  setHTML(".services .section-heading h2", t.servicesTitle);
  setText(".services .section-heading p", t.servicesQuestion);
  $$(".service-card").forEach((card, index) => {
    card.querySelector("h3").innerHTML = t.serviceTitles[index];
    card.querySelector("p").textContent = t.serviceDescriptions[index];
    card.querySelector("a").textContent = t.knowMore;
  });

  setText(".schedule__copy p", t.scheduleEyebrow);
  setHTML(".schedule h2", t.scheduleTitle);
  setText(".schedule .button", t.scheduleCta);

  setHTML(".plans .section-heading h2", t.plansTitle);
  setText(".plans .section-heading p:nth-of-type(1)", t.plansText);
  setText(".plans .section-heading p:nth-of-type(2)", t.plansRates);
  setText(".plan-card__details > div:nth-child(1) h3", t.basicTitle);
  setText(".plan-card__details > div:nth-child(1) p", t.basicDescription);
  setText(".plan-card__details > div:nth-child(2) h3", t.premiumTitle);
  setText(".plan-card__details > div:nth-child(2) p", t.premiumDescription);
  setText(".plan-card__prices strong:nth-child(1)", t.free);
  setText(".plan-card__prices strong:nth-child(2)", t.price);
  setText(".plan-card__prices .button", t.buyNow);

  setHTML(".testimonials .section-heading h2", t.customersTitle);
  $$(".stars").forEach((stars) => stars.setAttribute("aria-label", t.starsLabel));
  $$(".testimonial p").forEach((text, index) => {
    text.textContent = t.testimonials[index];
  });

  setHTML(".contact__copy h2", t.contactTitle);
  setText(".contact__copy p", t.contactCta);
  setText(".contact-form label:nth-child(1) span", t.fieldLabels.name);
  setText(".contact-form label:nth-child(2) span", t.fieldLabels.phone);
  setText(".contact-form label:nth-child(3) span", t.fieldLabels.address);
  setText(".contact-form label:nth-child(4) span", t.fieldLabels.district);
  setText(".contact-form label:nth-child(5) span", t.fieldLabels.device);
  setText(".contact-form label:nth-child(6) span", t.fieldLabels.email);
  setText(".contact-form label:nth-child(7) span", t.fieldLabels.message);
  setPlaceholder("input[name='nombre']", t.fields.name);
  setPlaceholder("input[name='telefono']", t.fields.phone);
  setPlaceholder("input[name='direccion']", t.fields.address);
  setPlaceholder("input[name='distrito']", t.fields.district);
  setPlaceholder("input[name='dispositivo']", t.fields.device);
  setPlaceholder("input[name='email']", t.fields.email);
  setPlaceholder("textarea[name='mensaje']", t.fields.message);
  setText(".contact-form .button", t.submit);

  setText(".footer__social h2", t.footerSocial);
  setText(".footer__subscribe h2", t.footerSubscribeTitle);
  setPlaceholder(".subscribe-form input", t.fields.email);
  setText(".subscribe-form button", t.footerSubscribeButton);
  setText(".footer__subscribe p", t.footerNote);
  setText(".footer__contact h2", t.footerLocation);
  setText(".footer__bottom p", t.rights);

  $$(selectors.langButtons).forEach((button) => {
    const isActive = button.dataset.lang === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("fixdevice-language", currentLanguage);
  setMenu(document.body.classList.contains("menu-open"));
}

function flashButton(button, text) {
  if (!button) return;

  const originalText = button.textContent;
  button.textContent = text;
  button.disabled = true;

  window.setTimeout(() => {
    button.textContent = originalText;
    button.disabled = false;
  }, 1800);
}

$(selectors.menuToggle)?.addEventListener("click", () => {
  setMenu(!document.body.classList.contains("menu-open"));
});

$(selectors.navBackdrop)?.addEventListener("click", () => setMenu(false));

$$(".main-nav a").forEach((link) => {
  link.addEventListener("click", () => setMenu(false));
});

$$(selectors.langButtons).forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.lang);
  });
});

$(selectors.contactForm)?.addEventListener("submit", (event) => {
  event.preventDefault();
  flashButton(event.currentTarget.querySelector("button"), translations[currentLanguage].sent);
  event.currentTarget.reset();
});

$(selectors.subscribeForm)?.addEventListener("submit", (event) => {
  event.preventDefault();
  flashButton(event.currentTarget.querySelector("button"), translations[currentLanguage].subscribed);
  event.currentTarget.reset();
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
});

window.matchMedia("(min-width: 901px)").addEventListener("change", (event) => {
  if (event.matches) setMenu(false);
});

applyLanguage(currentLanguage);
